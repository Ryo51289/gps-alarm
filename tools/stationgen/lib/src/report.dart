/// `data/stations/BUILD_REPORT.md` (spec T24 §4.9). Deterministic: no run
/// time, no machine specific data.
library;

import 'package:stationgen/src/acceptance.dart';
import 'package:stationgen/src/dedupe.dart';
import 'package:stationgen/src/model.dart';
import 'package:stationgen/src/prefixes.dart';
import 'package:stationgen/src/provinces.dart';
import 'package:stationgen/src/raw.dart';
import 'package:stationgen/src/writer.dart';

/// Lines listed per drop reason before "… and N more".
const int kMaxReportLines = 200;

/// A station whose admin areas map to more than one province.
final class ProvinceAmbiguity {
  const new(this.id, this.name, this.provinces, this.chosen);

  final String id;
  final String name;
  final List<String> provinces;
  final String chosen;
}

/// Everything the report shows.
final class ReportData {
  const new({
    required this.meta,
    required this.snapshot,
    required this.provinces,
    required this.stations,
    required this.fileBytes,
    required this.failures,
    required this.mustHave,
    required this.dropped,
    required this.nearDuplicates,
    required this.guessed,
    required this.ambiguities,
    required this.unmatchedAreas,
    required this.overridesApplied,
  });

  final FetchMeta meta;
  final OverpassSnapshot snapshot;
  final ProvinceTable provinces;
  final List<Candidate> stations;
  final int fileBytes;
  final List<AcceptanceFailure> failures;
  final List<MustHave> mustHave;
  final List<Dropped> dropped;
  final List<NearDuplicate> nearDuplicates;

  /// Candidates whose road kind was guessed, with "still in the output".
  final List<(Candidate, bool)> guessed;
  final List<ProvinceAmbiguity> ambiguities;
  final Map<String, int> unmatchedAreas;
  final List<String> overridesApplied;
}

String _st(Candidate c) => '`${c.id}` ${c.name}';

/// Markdown report, LF, trailing newline.
String buildReport(ReportData d) {
  final b = StringBuffer();
  void line([String s = '']) => b.write('$s\n');
  void none() => line('_None._');

  final counts = {for (final k in StationKind.values) k: 0};
  for (final s in d.stations) {
    counts[s.kind] = counts[s.kind]! + 1;
  }
  final merged = d.stations.fold<int>(0, (n, s) => n + s.mergedIds.length);

  line('# Station dataset build report');
  line();
  line(
    'Generated by `stationgen build` from `data/stations/raw/`. Do not edit; '
    'see `data/stations/README.md`.',
  );
  line();
  line('## 1. Summary');
  line();
  line('| Item | Value |');
  line('|---|---|');
  line('| OSM base (`osmBase`) | ${d.meta.osmBase} |');
  line('| Areas base | ${d.meta.areasBase ?? 'n/a'} |');
  line('| Overpass endpoint | ${d.meta.endpoint} |');
  line('| Generator | $kGeneratorName $kGeneratorVersion |');
  line('| Elements in snapshot (part A) | ${d.snapshot.elements.length} |');
  line('| Admin areas in snapshot (part B) | ${d.snapshot.groups.length} |');
  line(
    '| Stations | ${d.stations.length} (train ${counts[StationKind.train]}, '
    'coach ${counts[StationKind.coach]}, bus ${counts[StationKind.bus]}) |',
  );
  line('| Dropped elements | ${d.dropped.length} |');
  line('| Merged duplicates | $merged |');
  line('| `stations.json` size | ${d.fileBytes} bytes |');
  line();
  line('Acceptance (spec T24 §4.7):');
  line();
  const checks = {
    'A1': 'at least $kMinTrainStations train stations',
    'A2': 'every province has a coach station',
    'A3': 'every must-have entry found (waived entries excluded)',
    'A4': 'unique ids, valid names, coordinates and provinces',
    'A5': 'at most $kMaxStations stations and $kMaxFileBytes bytes',
  };
  for (final MapEntry(key: code, value: text) in checks.entries) {
    final f = d.failures.where((x) => x.code == code).toList();
    line('- $code ${f.isEmpty ? 'PASS' : 'FAIL'}: $text');
    for (final x in f) {
      line('  - ${x.message}${x.items.isEmpty ? '' : ':'}');
      for (final item in x.items) {
        line('    - $item');
      }
    }
  }
  line();

  line('## 2. Stations per province');
  line();
  line('| Province | train | coach | bus |');
  line('|---|---:|---:|---:|');
  final names = [...d.provinces.names]
    ..sort((a, b) => provinceKey(a).compareTo(provinceKey(b)));
  for (final p in names) {
    int n(StationKind k) =>
        d.stations.where((s) => s.province == p && s.kind == k).length;
    line(
      '| $p | ${n(StationKind.train)} | ${n(StationKind.coach)} | '
      '${n(StationKind.bus)} |',
    );
  }
  line(
    '| **Total** | ${counts[StationKind.train]} | '
    '${counts[StationKind.coach]} | ${counts[StationKind.bus]} |',
  );
  line();

  line('## 3. Must-have');
  line();
  if (d.mustHave.isEmpty) {
    none();
  }
  for (final m in d.mustHave) {
    final s = findMustHave(m, d.stations);
    final what = '${m.kind.name} `${m.match}` (${m.province})';
    if (m.waived != null) {
      line(
        s == null
            ? '- ⚠ $what: waived — ${m.waived}'
            : '- ✓ $what: ${_st(s)} (waived entry is found now; remove '
                  'the waiver)',
      );
      continue;
    }
    line(s == null ? '- ✗ $what: not found' : '- ✓ $what: ${_st(s)}');
  }
  line();

  line('## 4. Dropped');
  line();
  if (d.dropped.isEmpty) {
    none();
  } else {
    line('| Reason | Count |');
    line('|---|---:|');
    for (final r in DropReason.values) {
      final n = d.dropped.where((x) => x.reason == r).length;
      if (n > 0) {
        line('| ${r.label} | $n |');
      }
    }
    for (final r in DropReason.values) {
      final list = d.dropped.where((x) => x.reason == r).toList()
        ..sort((a, b) => a.id.compareTo(b.id));
      if (list.isEmpty) {
        continue;
      }
      line();
      line('### ${r.label} (${list.length})');
      line();
      for (final x in list.take(kMaxReportLines)) {
        line('- `${x.id}` — ${x.name ?? '(no name)'}');
      }
      if (list.length > kMaxReportLines) {
        line('- … and ${list.length - kMaxReportLines} more');
      }
    }
  }
  line();

  line('## 5. Merged duplicates');
  line();
  final withMerged = d.stations.where((s) => s.mergedIds.isNotEmpty).toList();
  if (withMerged.isEmpty) {
    none();
  }
  for (final s in withMerged) {
    line('- ${_st(s)} ← ${s.mergedIds.map((i) => '`$i`').join(', ')}');
  }
  line();

  line('## 6. Near-duplicates (same kind, ≤ ${kNearDuplicateM.round()} m)');
  line();
  if (d.nearDuplicates.isEmpty) {
    none();
  }
  for (final n in d.nearDuplicates) {
    line(
      '- ${n.a.kind.name}: ${_st(n.a)} ↔ ${_st(n.b)} — '
      '${n.distanceM.round()} m',
    );
  }
  line();

  line('## 7. Kind guessed (road station without evidence, kept as bus)');
  line();
  final guessed = [...d.guessed]..sort((a, b) => a.$1.id.compareTo(b.$1.id));
  if (guessed.isEmpty) {
    none();
  }
  for (final (c, kept) in guessed) {
    line('- ${_st(c)} (${c.province})${kept ? '' : ' — merged'}');
  }
  line();

  line('## 8. Province ambiguities');
  line();
  if (d.ambiguities.isEmpty) {
    none();
  }
  for (final a in [...d.ambiguities]..sort((x, y) => x.id.compareTo(y.id))) {
    line('- `${a.id}` ${a.name}: ${a.provinces.join(', ')} → ${a.chosen}');
  }
  line();

  line('## 9. Unmatched admin areas');
  line();
  final areas = d.unmatchedAreas.keys.toList()..sort();
  if (areas.isEmpty) {
    none();
  }
  for (final a in areas) {
    line('- $a (${d.unmatchedAreas[a]} elements)');
  }
  line();

  line('## 10. Decomposed names (NFD)');
  line();
  final decomposed = d.stations
      .where((s) => s.name.runes.any((r) => r >= 0x300 && r <= 0x36F))
      .toList();
  if (decomposed.isEmpty) {
    none();
  }
  for (final s in decomposed) {
    line('- ${_st(s)}');
  }
  line();

  line('## 11. Overrides applied');
  line();
  if (d.overridesApplied.isEmpty) {
    none();
  }
  for (final o in d.overridesApplied) {
    line('- $o');
  }
  line();

  line('## 12. Train stations in Hà Nội and TP. Hồ Chí Minh (metro review)');
  line();
  final review = d.stations
      .where(
        (s) =>
            s.kind == StationKind.train &&
            (s.province == 'Hà Nội' || s.province == 'TP. Hồ Chí Minh'),
      )
      .toList();
  if (review.isEmpty) {
    none();
  }
  for (final s in review) {
    line('- ${_st(s)} (${s.province})');
  }
  return b.toString();
}
