/// `data/stations/BUS_BUILD_REPORT.md` (spec T24.3 §4). Deterministic: no
/// run time, no machine specific data.
library;

import 'package:stationgen/src/acceptance.dart';
import 'package:stationgen/src/acceptance_bus.dart';
import 'package:stationgen/src/merge_bus.dart';
import 'package:stationgen/src/model.dart';
import 'package:stationgen/src/model_bus.dart';
import 'package:stationgen/src/raw.dart';
import 'package:stationgen/src/report.dart';
import 'package:stationgen/src/writer.dart';

/// Largest merged clusters listed in section 4.
const int kMaxLargestClusters = 20;

/// A stop dropped because a bus/coach station already covers it.
typedef DupOfStation = (BusCandidate stop, Candidate station, double metres);

/// A `route_ref` value that was cut or dropped (D7).
typedef RouteRefIssue = (String id, String raw);

/// Everything the bus report shows.
final class BusReportData {
  const new({
    required this.meta,
    required this.snapshot,
    required this.provinces,
    required this.requiredProvinces,
    required this.stops,
    required this.fileBytes,
    required this.failures,
    required this.mustHave,
    required this.dropped,
    required this.dupOfStation,
    required this.nearSameName,
    required this.routesTruncated,
    required this.routesInvalid,
    required this.ambiguities,
    required this.areas,
    required this.overridesApplied,
  });

  final FetchMeta meta;
  final OverpassSnapshot snapshot;

  /// Provinces of the output, in file order.
  final List<String> provinces;
  final List<String> requiredProvinces;

  /// Final stops in output order.
  final List<BusStop> stops;
  final int fileBytes;
  final List<AcceptanceFailure> failures;
  final List<BusMustHave> mustHave;

  /// Dropped elements (DUP_OF_STATION included).
  final List<BusDropped> dropped;
  final List<DupOfStation> dupOfStation;
  final List<NearSameName> nearSameName;
  final List<RouteRefIssue> routesTruncated;
  final List<RouteRefIssue> routesInvalid;
  final List<ProvinceAmbiguity> ambiguities;

  /// Admin areas of part B: (name, resolved province or null, elements).
  final List<(String, String?, int)> areas;
  final List<String> overridesApplied;
}

String _st(BusStop s) => '`${s.id}` ${s.name}';

/// Markdown report, LF, trailing newline.
String buildBusReport(BusReportData d) {
  final b = StringBuffer();
  void line([String s = '']) => b.write('$s\n');
  void none() => line('_None._');
  void capped<T>(List<T> items, String Function(T) text) {
    if (items.isEmpty) {
      none();
      return;
    }
    for (final x in items.take(kMaxReportLines)) {
      line(text(x));
    }
    if (items.length > kMaxReportLines) {
      line('- … and ${items.length - kMaxReportLines} more');
    }
  }

  final candidates = d.stops.fold<int>(0, (n, s) => n + s.members.length);
  final withRoutes = d.stops.where((s) => s.routes.isNotEmpty).length;

  line('# Bus stop dataset build report');
  line();
  line(
    'Generated by `stationgen build` from `data/stations/raw/bus_*`. Do not '
    'edit; see `data/stations/README.md`.',
  );
  line();
  line('## 1. Summary');
  line();
  line('| Item | Value |');
  line('|---|---|');
  line('| OSM base (`osmBase`) | ${d.meta.osmBase} |');
  line('| Areas base | ${d.meta.areasBase ?? 'n/a'} |');
  line('| Overpass endpoint | ${d.meta.endpoint} |');
  line('| Generator | $kGeneratorName $kGeneratorVersion |');
  line('| Elements in snapshot (part A) | ${d.snapshot.elements.length} |');
  line('| Admin areas in snapshot (part B) | ${d.snapshot.groups.length} |');
  line('| Dropped elements | ${d.dropped.length} |');
  line('| Candidates before merging sides | $candidates |');
  line('| Bus stops after merging sides | ${d.stops.length} |');
  line('| Stops with routes | $withRoutes |');
  line('| `bus_stops.json` size | ${d.fileBytes} bytes |');
  line();
  line('Admin areas (part B):');
  line();
  for (final (area, province, n) in d.areas) {
    line('- $area → ${province ?? '(unmatched)'} ($n elements)');
  }
  line();
  line('Acceptance (spec T24.3 §4):');
  line();
  const checks = {
    'B1': 'every city has at least $kMinBusStopsPerProvince stops',
    'B2': 'unique ids, valid names, coordinates, routes and provinces',
    'B3': 'at most $kMaxBusStops stops and $kMaxBusFileBytes bytes',
    'B4': 'every must-have entry found',
  };
  for (final MapEntry(key: code, value: text) in checks.entries) {
    final f = d.failures.where((x) => x.code == code).toList();
    line('- $code ${f.isEmpty ? 'PASS' : 'FAIL'}: $text');
    for (final x in f) {
      line('  - ${x.message}${x.items.isEmpty ? '' : ':'}');
      for (final item in x.items.take(kMaxReportLines)) {
        line('    - $item');
      }
    }
  }
  line();
  line('Must-have:');
  line();
  if (d.mustHave.isEmpty) {
    none();
  }
  for (final m in d.mustHave) {
    final s = findBusMustHave(m, d.stops);
    line(
      s == null
          ? '- ✗ `${m.match}` (${m.province}): not found'
          : '- ✓ `${m.match}` (${m.province}): ${_st(s)}',
    );
  }
  line();

  line('## 2. Stops per province');
  line();
  line('| Province | Stops | With routes |');
  line('|---|---:|---:|');
  final provinces = [
    ...d.provinces,
    for (final p in d.requiredProvinces)
      if (!d.provinces.contains(p)) p,
  ];
  for (final p in provinces) {
    final list = d.stops.where((s) => s.province == p);
    line(
      '| $p | ${list.length} | '
      '${list.where((s) => s.routes.isNotEmpty).length} |',
    );
  }
  line('| **Total** | ${d.stops.length} | $withRoutes |');
  line();

  line('## 3. Dropped');
  line();
  if (d.dropped.isEmpty) {
    none();
  } else {
    line('| Reason | Count |');
    line('|---|---:|');
    for (final r in BusDropReason.values) {
      final n = d.dropped.where((x) => x.reason == r).length;
      if (n > 0) {
        line('| ${r.label} | $n |');
      }
    }
    for (final r in BusDropReason.values) {
      final list = d.dropped.where((x) => x.reason == r).toList()
        ..sort((a, b) => a.id.compareTo(b.id));
      if (list.isEmpty) {
        continue;
      }
      line();
      line('### ${r.label} (${list.length})');
      line();
      capped(list, (x) => '- `${x.id}` — ${x.name ?? '(no name)'}');
    }
  }
  line();

  line('## 4. Merged sides (same name, ≤ ${kBusMergeRadiusM.round()} m)');
  line();
  int clusters(bool Function(int) size) =>
      d.stops.where((s) => size(s.members.length)).length;
  line('| Members | Stops |');
  line('|---|---:|');
  line('| 1 | ${clusters((n) => n == 1)} |');
  line('| 2 | ${clusters((n) => n == 2)} |');
  line('| 3 | ${clusters((n) => n == 3)} |');
  line('| ≥ 4 | ${clusters((n) => n >= 4)} |');
  line();
  final largest = d.stops.where((s) => s.members.length > 1).toList()
    ..sort((a, b) {
      final c = b.members.length.compareTo(a.members.length);
      return c != 0 ? c : a.id.compareTo(b.id);
    });
  line('Largest clusters:');
  line();
  if (largest.isEmpty) {
    none();
  }
  for (final s in largest.take(kMaxLargestClusters)) {
    line(
      '- ${_st(s)} (${s.province}) ← '
      '${s.members.skip(1).map((m) => '`${m.id}`').join(', ')}',
    );
  }
  line();

  line(
    '## 5. Duplicate of a bus/coach station (same core name, '
    '≤ ${kDupOfStationM.round()} m)',
  );
  line();
  final dups = [...d.dupOfStation]..sort((a, b) => a.$1.id.compareTo(b.$1.id));
  capped(
    dups,
    (x) =>
        '- `${x.$1.id}` ${x.$1.name} → `${x.$2.id}` ${x.$2.name} — '
        '${x.$3.round()} m',
  );
  line();

  line(
    '## 6. Near same name (same name, ${kBusMergeRadiusM.round()}–'
    '${kBusNearSameNameM.round()} m, not merged)',
  );
  line();
  capped(
    d.nearSameName,
    (n) => '- ${_st(n.a)} ↔ `${n.b.id}` — ${n.distanceM.round()} m',
  );
  line();

  line('## 7. route_ref');
  line();
  line('| Item | Count |');
  line('|---|---:|');
  line('| Stops with routes | $withRoutes |');
  line('| Values cut to 6 routes | ${d.routesTruncated.length} |');
  line(
    '| Values dropped (a route longer than 8 characters) | '
    '${d.routesInvalid.length} |',
  );
  for (final (title, list) in [
    ('Cut', d.routesTruncated),
    ('Dropped', d.routesInvalid),
  ]) {
    if (list.isEmpty) {
      continue;
    }
    line();
    line('### $title (${list.length})');
    line();
    final sorted = [...list]..sort((a, b) => a.$1.compareTo(b.$1));
    capped(sorted, (x) => '- `${x.$1}` — `${x.$2}`');
  }
  line();

  line('## 8. Province ambiguities');
  line();
  final amb = [...d.ambiguities]..sort((x, y) => x.id.compareTo(y.id));
  capped(
    amb,
    (a) => '- `${a.id}` ${a.name}: ${a.provinces.join(', ')} → ${a.chosen}',
  );
  line();

  line('## 9. Overrides applied');
  line();
  if (d.overridesApplied.isEmpty) {
    none();
  }
  for (final o in d.overridesApplied) {
    line('- $o');
  }
  return b.toString();
}
