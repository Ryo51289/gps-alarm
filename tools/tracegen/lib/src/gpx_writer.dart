/// Byte-exact GPX 1.1 writer (spec T02 §7.2).
library;

import 'package:tracegen/src/fmt.dart';
import 'package:tracegen/src/sensor.dart';

/// GPX 1.1 namespace.
const String kGpxNamespace = 'http://www.topografix.com/GPX/1/1';

/// Namespace of the `napstop:` extension elements.
const String kNapstopNamespace = 'https://napstop.app/xmlns/trace/1';

/// Content of the track to write.
final class GpxTrack {
  const new({
    required this.id,
    required this.title,
    required this.vehicle,
    required this.startEpochS,
    required this.segments,
  });

  final String id;
  final String title;
  final String vehicle;
  final int startEpochS;

  /// One list per `trkseg` (a new segment after every GPS gap).
  final List<List<Observation>> segments;
}

const String _odbl = 'https://opendatacommons.org/licenses/odbl/1-0/';

/// Escapes `& < > " '` for XML text and attribute values.
String xmlEscape(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');

/// One `trkpt` line (without indentation and newline).
String gpxTrackPoint(Observation o, int startEpochS) {
  final sb = StringBuffer()
    ..write('<trkpt lat="')
    ..write(fmt(o.pos.lat, 7))
    ..write('" lon="')
    ..write(fmt(o.pos.lng, 7))
    ..write('"><time>')
    ..write(isoUtc(startEpochS, o.t))
    ..write('</time><extensions><napstop:acc>')
    ..write(fmt(o.accM, 1))
    ..write('</napstop:acc>');
  final speed = o.speedMps;
  if (speed != null) {
    sb
      ..write('<napstop:spd>')
      ..write(fmt(speed, 2))
      ..write('</napstop:spd>');
  }
  sb.write('</extensions></trkpt>');
  return sb.toString();
}

/// Full GPX document, LF line endings, trailing newline.
String writeGpx(GpxTrack track) {
  final id = xmlEscape(track.id);
  final sb = StringBuffer()
    ..write('<?xml version="1.0" encoding="UTF-8"?>\n')
    ..write(
      '<gpx version="1.1" creator="NapStop tracegen" '
      'xmlns="$kGpxNamespace" '
      'xmlns:napstop="$kNapstopNamespace" '
      'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
      'xsi:schemaLocation="$kGpxNamespace '
      'http://www.topografix.com/GPX/1/1/gpx.xsd">\n',
    )
    ..write('  <metadata>\n')
    ..write('    <name>$id</name>\n')
    ..write(
      '    <desc>Synthetic trace generated by NapStop tracegen. '
      'Not a real journey.</desc>\n',
    )
    ..write('    <copyright author="OpenStreetMap contributors">\n')
    ..write('      <license>$_odbl</license>\n')
    ..write('    </copyright>\n')
    ..write('    <time>${isoUtc(track.startEpochS, 0)}</time>\n')
    ..write('  </metadata>\n')
    ..write('  <trk>\n')
    ..write('    <name>$id</name>\n')
    ..write('    <desc>${xmlEscape(track.title)}</desc>\n')
    ..write('    <type>${xmlEscape(track.vehicle)}</type>\n');
  for (final segment in track.segments) {
    sb.write('    <trkseg>\n');
    for (final o in segment) {
      sb
        ..write('      ')
        ..write(gpxTrackPoint(o, track.startEpochS))
        ..write('\n');
    }
    sb.write('    </trkseg>\n');
  }
  sb
    ..write('  </trk>\n')
    ..write('</gpx>\n');
  return sb.toString();
}
