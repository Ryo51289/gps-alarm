// Expected output is split into adjacent literals at arbitrary points.
// ignore_for_file: missing_whitespace_between_adjacent_strings

import 'package:test/test.dart';
import 'package:tracegen/tracegen.dart';
import 'package:xml/xml.dart';

void main() {
  group('writeGpx (TC18)', () {
    final start = parseIsoUtc('2026-03-14T02:00:00Z');
    final track = GpxTrack(
      id: 'demo_trace',
      title: 'A & B <C> "D" \'E\' → Đ',
      vehicle: 'coach',
      startEpochS: start,
      segments: [
        [
          const Observation(
            t: 0,
            pos: LatLng(16.05501, 108.1733575),
            accM: 6.14,
            speedMps: 0.123,
          ),
          const Observation(t: 5, pos: LatLng(16.0551, 108.17336), accM: 3),
        ],
        [
          const Observation(
            t: 365,
            pos: LatLng(-0.00000001, 108),
            accM: 25,
            speedMps: 0,
          ),
        ],
      ],
    );
    final text = writeGpx(track);
    final lines = text.split('\n');

    test('header matches the fixture format byte for byte', () {
      const header =
          '<?xml version="1.0" encoding="UTF-8"?>\n'
          '<gpx version="1.1" creator="NapStop tracegen" '
          'xmlns="http://www.topografix.com/GPX/1/1" '
          'xmlns:napstop="https://napstop.app/xmlns/trace/1" '
          'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
          'xsi:schemaLocation="http://www.topografix.com/GPX/1/1 '
          'http://www.topografix.com/GPX/1/1/gpx.xsd">\n'
          '  <metadata>\n'
          '    <name>demo_trace</name>\n'
          '    <desc>Synthetic trace generated by NapStop tracegen. '
          'Not a real journey.</desc>\n'
          '    <copyright author="OpenStreetMap contributors">\n'
          '      <license>https://opendatacommons.org/licenses/odbl/1-0/'
          '</license>\n'
          '    </copyright>\n'
          '    <time>2026-03-14T02:00:00Z</time>\n'
          '  </metadata>\n'
          '  <trk>\n'
          '    <name>demo_trace</name>\n'
          '    <desc>A &amp; B &lt;C&gt; &quot;D&quot; &apos;E&apos; → Đ'
          '</desc>\n'
          '    <type>coach</type>\n'
          '    <trkseg>\n';
      expect(text.startsWith(header), isTrue, reason: text);
      expect(text.endsWith('    </trkseg>\n  </trk>\n</gpx>\n'), isTrue);
      expect(text.contains('\r'), isFalse);
    });

    test('writes one trkpt per line', () {
      expect(
        lines[15],
        '      <trkpt lat="16.0550100" lon="108.1733575">'
        '<time>2026-03-14T02:00:00Z</time><extensions>'
        '<napstop:acc>6.1</napstop:acc><napstop:spd>0.12</napstop:spd>'
        '</extensions></trkpt>',
      );
      expect(
        lines[16],
        '      <trkpt lat="16.0551000" lon="108.1733600">'
        '<time>2026-03-14T02:00:05Z</time><extensions>'
        '<napstop:acc>3.0</napstop:acc></extensions></trkpt>',
      );
      expect(
        lines[19],
        '      <trkpt lat="0.0000000" lon="108.0000000">'
        '<time>2026-03-14T02:06:05Z</time><extensions>'
        '<napstop:acc>25.0</napstop:acc><napstop:spd>0.00</napstop:spd>'
        '</extensions></trkpt>',
      );
    });

    test('opens a new trkseg after a gap and parses as XML', () {
      expect('<trkseg>'.allMatches(text), hasLength(2));
      final doc = XmlDocument.parse(text);
      final points = doc.findAllElements('trkpt', namespaceUri: kGpxNamespace);
      expect(points, hasLength(3));
      final title = doc.rootElement
          .getElement('trk', namespaceUri: kGpxNamespace)!
          .getElement('desc', namespaceUri: kGpxNamespace)!
          .innerText;
      expect(title, track.title);
    });
  });
}
