// D09-D11 (spec T14): privacy and setup checks on the Pigeon input and the
// bridge sources.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const _input = 'pigeons/core_api.dart';

/// [text] without `//` comments (doc comments included).
String _stripComments(String text) =>
    text.split('\n').map((l) => l.replaceFirst(RegExp('//.*'), '')).join('\n');

/// Identifiers that look like a coordinate (review T14 N2). `location` is not
/// one: `PermissionStatusMsg.location` is a permission state.
final _coordinate = RegExp(
  r'\b(lat|lng|lon|latitude|longitude|coords?|coordinates?|geo\w*|position'
  r'|\w*E7|\w+(Lat|Lng|Lon|Latitude|Longitude|Coords?|Coordinates?|Position))\b',
  caseSensitive: false,
);

void main() {
  test('D09 pattern catches coordinate-like names only', () {
    for (final name in [
      'lat',
      'lng',
      'lon',
      'latitude',
      'longitude',
      'coord',
      'coords',
      'coordinates',
      'geoPoint',
      'position',
      'latE7',
      'destLat',
      'destLng',
      'destLon',
      'userLongitude',
      'stopCoords',
      'lastPosition',
    ]) {
      expect(_coordinate.hasMatch('double $name;'), isTrue, reason: name);
    }
    for (final name in ['location', 'destinationName', 'distanceM', 'etaS']) {
      expect(_coordinate.hasMatch('double $name;'), isFalse, reason: name);
    }
  });

  test('D09 no Pigeon class holds coordinates', () {
    final code = _stripComments(File(_input).readAsStringSync());
    final names = _coordinate.allMatches(code).map((m) => m.group(0)).toList();
    expect(names, ['destLat', 'destLng']);

    // Both are parameters of TripHostApi.startTrip, not class fields.
    final startTrip = RegExp(r'void startTrip\(([^)]*)\)').firstMatch(code);
    expect(startTrip, isNotNull);
    final params = startTrip!.group(1)!;
    expect(params, contains('double destLat'));
    expect(params, contains('double destLng'));
    final apiStart = code.indexOf('abstract class TripHostApi');
    expect(apiStart, greaterThan(0));
    expect(code.indexOf('destLat'), greaterThan(apiStart));
  });

  test('D10 no logging in lib/core/bridge (hand-written files)', () {
    final files = Directory('lib/core/bridge')
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart') && !f.path.endsWith('.g.dart'))
        .toList();
    expect(files.length, greaterThanOrEqualTo(2));
    final forbidden = <String, RegExp>{
      'print(': RegExp(r'\bprint\('),
      'debugPrint(': RegExp(r'\bdebugPrint\('),
      'log(': RegExp(r'\blog\('),
      'developer.log': RegExp(r'developer\.log'),
      'dart:developer': RegExp('dart:developer'),
    };
    for (final f in files) {
      final text = f.readAsStringSync();
      for (final MapEntry(key: label, value: re) in forbidden.entries) {
        expect(re.hasMatch(text), isFalse, reason: '$label in ${f.path}');
      }
    }
  });

  test('D11 Pigeon output configuration', () {
    final code = File(_input).readAsStringSync();
    final start = code.indexOf('@ConfigurePigeon(');
    expect(start, greaterThanOrEqualTo(0));
    final block = code.substring(start, code.indexOf('\n)\n', start));
    expect(block, contains("dartOut: 'lib/core/bridge/core_api.g.dart'"));
    expect(
      block,
      contains(
        "kotlinOptions: KotlinOptions(package: 'app.napstop.core.bridge')",
      ),
    );
    expect(block, contains("dartPackageName: 'napstop'"));
    expect(
      block,
      contains(
        "'android/app/src/main/kotlin/app/napstop/core/bridge/CoreApi.g.kt'",
      ),
    );
    expect(block, contains("swiftOut: 'ios/Runner/Bridge/CoreApi.g.swift'"));
    for (final out in [
      'lib/core/bridge/core_api.g.dart',
      'android/app/src/main/kotlin/app/napstop/core/bridge/CoreApi.g.kt',
      'ios/Runner/Bridge/CoreApi.g.swift',
    ]) {
      final file = File(out);
      expect(file.existsSync(), isTrue, reason: out);
      expect(
        file.readAsStringSync(),
        startsWith('// Autogenerated from Pigeon (v29.1.0)'),
        reason: out,
      );
    }
  });

  test('pigeon is pinned exactly', () {
    expect(
      File('pubspec.yaml').readAsStringSync(),
      contains(RegExp(r'^  pigeon: 29\.1\.0$', multiLine: true)),
    );
  });
}
