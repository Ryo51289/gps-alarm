package app.napstop.core.bridge

import org.junit.Assert.assertEquals
import org.junit.Assert.fail
import org.junit.Test
import java.io.File

/**
 * Tester T17.1: one table of `LastKnownMath` inputs and the Kotlin answers, shared with the Swift port
 * (`app/ios/Core/Tests/TripRuntimeTests/Unit/LastKnownParityTests.swift` reads the same file and must give the same
 * bits). Kotlin is the reference (T23).
 *
 * `fixtures/parity/last_known_math.json` missing → written, then this test fails once ("run again"), like
 * `RuntimeFirstAlarmExportTest`. A deliberate change of the Kotlin rule → delete the file, run twice, commit.
 * Doubles travel as the hex of their IEEE-754 bits, so NaN, infinities and every last bit survive.
 */
class LastKnownMathParityExportTest {
    private fun repoRoot(): File {
        System.getProperty("napstop.l10nDir")?.let { return File(it).absoluteFile.parentFile.parentFile.parentFile }
        var d: File? = File("").absoluteFile
        while (d != null && !File(d, "fixtures/traces").isDirectory) d = d.parentFile
        return d ?: error("repository root not found")
    }

    private fun golden(): File = File(repoRoot(), "fixtures/parity/last_known_math.json")

    private fun hex(x: Double): String =
        java.lang.Long.toHexString(java.lang.Double.doubleToRawLongBits(x)).padStart(16, '0')

    /** Deterministic inputs: boundaries, every half step up to 10 km, a fixed-seed spread up to 500 km. */
    private fun roundInputs(): List<Double> {
        val out = mutableListOf(
            Double.NaN, Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY, -0.0, 0.0, -1.0, Double.MIN_VALUE,
            4.9, 4.999999999999999, 5.0, 847.3, 994.0, 994.9, 994.99, 994.9999999999999, 995.0, 999.4, 999.9,
            999.9999999999999, 1000.0, 1000.0000000000002, 1049.0, 1049.9, 1050.0, 1450.0, 12_345.0, 402_031.7,
            1.0e7, 2.0e7,
        )
        for (i in 0..4000) out.add(i * 2.5) // 0 … 10 000 m: every x5 (10 m half step) and x50 (100 m half step)
        var seed = 0x2545F4914F6CDD1DL
        repeat(500) {
            seed = seed * 6364136223846793005L + 1442695040888963407L
            val u = (seed ushr 11).toDouble() / (1L shl 53).toDouble()
            out.add(u * 500_000.0)
        }
        return out
    }

    private fun pairInputs(): List<List<Double>> = listOf(
        emptyList(),
        listOf(16.0),
        listOf(21.0, 105.8),
        List(100) { 10.0 },
        List(101) { 10.0 },
        List(102) { 10.0 },
        listOf(Double.NaN, 105.8),
        listOf(21.0, Double.POSITIVE_INFINITY),
        listOf(Double.NEGATIVE_INFINITY, 0.0),
        listOf(90.0, 180.0, -90.0, -180.0),
        listOf(90.0001, 0.0),
        listOf(-90.0001, 0.0),
        listOf(0.0, 180.0001),
        listOf(0.0, -180.0001),
        listOf(91.0, 105.8),
        listOf(21.0, 180.5),
        listOf(-0.0, -0.0),
        listOf(17.4689199, 106.5997285, 16.8163, 107.1003),
        listOf(17.4689199, 106.5997285, 16.8163),
    )

    private val ages = listOf(-86_400_000L, -5_000L, -1L, 0L, 1L, 59_999L, 60_000L, 60_001L, 599_999L, 600_000L,
        600_001L, 1_799_999L, 1_800_000L, 1_800_001L, 86_400_000L)
    private val maxAges = listOf(0L, 1L, 60_000L, 600_000L, 1_800_000L)

    private fun table(): String {
        val sb = StringBuilder()
        sb.append("{\n  \"comment\": \"Generated by LastKnownMathParityExportTest.kt (Kotlin LastKnownMath, T23). ")
        sb.append("Doubles are IEEE-754 bit patterns in hex. Do not edit by hand.\",\n")
        sb.append("  \"roundForDisplay\": [\n")
        val r = roundInputs()
        r.forEachIndexed { i, m ->
            sb.append("    {\"in\": \"").append(hex(m)).append("\", \"out\": \"")
                .append(hex(LastKnownMath.roundForDisplay(m))).append("\"}")
            sb.append(if (i < r.size - 1) ",\n" else "\n")
        }
        sb.append("  ],\n  \"validPairs\": [\n")
        val p = pairInputs()
        p.forEachIndexed { i, list ->
            sb.append("    {\"in\": [").append(list.joinToString(", ") { "\"${hex(it)}\"" }).append("], \"out\": ")
                .append(LastKnownMath.validPairs(list)).append("}")
            sb.append(if (i < p.size - 1) ",\n" else "\n")
        }
        sb.append("  ],\n  \"fresh\": [\n")
        val nowNs = 10_000_000_000_000_000L
        val rows = mutableListOf<String>()
        for (max in maxAges) {
            for (age in ages) {
                val fresh = LastKnownMath.freshest(
                    listOf(LastKnownMath.Candidate(nowNs - age * 1_000_000L)), nowNs, max,
                ) != null
                rows.add("    {\"ageMs\": $age, \"maxAgeMs\": $max, \"fresh\": $fresh}")
            }
        }
        sb.append(rows.joinToString(",\n")).append("\n  ]\n}\n")
        return sb.toString()
    }

    @Test
    fun goldenMatchesKotlin() {
        val text = table()
        val f = golden()
        if (!f.exists()) {
            f.parentFile.mkdirs()
            f.writeText(text, Charsets.UTF_8)
            fail("${f.path} was missing and has been written; run again")
        }
        assertEquals("fixtures/parity/last_known_math.json differs from Kotlin LastKnownMath", text, f.readText(Charsets.UTF_8))
    }
}
